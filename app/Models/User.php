<?php

namespace App\Models;

use Database\Factories\UserFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Laravel\Sanctum\HasApiTokens;

class User extends Authenticatable
{
    /** @use HasFactory<UserFactory> */
    use HasApiTokens, HasFactory, Notifiable, SoftDeletes;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'name',
        'email',
        'password',
        'is_super_admin',
        'avatar_url',
        'phone',
        'status',
    ];

    /**
     * The attributes that should be hidden for serialization.
     *
     * @var list<string>
     */
    protected $hidden = [
        'password',
        'remember_token',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'password' => 'hashed',
            'is_super_admin' => 'boolean',
        ];
    }

    /**
     * Websites owned by this user.
     */
    public function websites(): HasMany
    {
        return $this->hasMany(Website::class);
    }

    /**
     * Roles assigned to this user, optionally scoped to a website.
     */
    public function roles(): BelongsToMany
    {
        return $this->belongsToMany(Role::class, 'role_user')
            ->withPivot('website_id')
            ->withTimestamps();
    }

    /**
     * Check if user has a specific role (globally or on a website).
     */
    public function hasRole(string $roleSlug, ?int $websiteId = null): bool
    {
        if ($this->is_super_admin) {
            return true;
        }

        return $this->roles()
            ->where('slug', $roleSlug)
            ->where(function ($q) use ($websiteId) {
                $q->whereNull('role_user.website_id');
                if ($websiteId !== null) {
                    $q->orWhere('role_user.website_id', $websiteId);
                }
            })
            ->exists();
    }

    /**
     * Check if user has a specific permission.
     */
    public function hasPermission(string $permissionSlug, ?int $websiteId = null): bool
    {
        if ($this->is_super_admin) {
            return true;
        }

        return $this->roles()
            ->where(function ($q) use ($websiteId) {
                $q->whereNull('role_user.website_id');
                if ($websiteId !== null) {
                    $q->orWhere('role_user.website_id', $websiteId);
                }
            })
            ->whereHas('permissions', function ($q) use ($permissionSlug) {
                $q->where('slug', $permissionSlug);
            })
            ->exists();
    }

    /**
     * Activity logs generated by this user.
     */
    public function activityLogs(): HasMany
    {
        return $this->hasMany(ActivityLog::class);
    }
}
